"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { loadSession, updateSession, type SimSession } from "@/lib/session";
import { AppPage, SimNote } from "@/components/app/AppPage";

/**
 * /notifications — the observed NotificationGallery. Kind badges, mark-read
 * and mark-all-read (client-side extension of the observed surface).
 */
export default function NotificationsPage() {
  const [session, setSession] = useState<SimSession | null>(null);

  useEffect(() => setSession(loadSession()), []);

  if (!session) {
    return (
      <main className="flex min-h-screen items-center justify-center bg-surface-base">
        <Link href="/login" className="text-sm underline underline-offset-2">Sign in to see notifications</Link>
      </main>
    );
  }

  const notifications = session.notifications;
  const unread = notifications.filter((n) => !n.read).length;

  function markRead(id: string) {
    updateSession((s) => ({ ...s, notifications: s.notifications.map((n) => (n.id === id ? { ...n, read: true } : n)) }));
    setSession(loadSession());
  }

  function markAll() {
    updateSession((s) => ({ ...s, notifications: s.notifications.map((n) => ({ ...n, read: true })) }));
    setSession(loadSession());
  }

  const tone: Record<string, string> = {
    invite: "bg-accent-subtle text-accent-subtle-foreground",
    credits: "bg-surface-raised text-content-primary",
    system: "bg-surface-raised text-content-secondary",
    model: "bg-surface-raised text-content-primary",
  };

  return (
    <AppPage
      section="notifications"
      title="Notifications"
      subtitle={unread ? `${unread} unread` : "All caught up"}
      wide
    >
      {unread > 0 && (
        <div className="mb-4 flex justify-end">
          <button
            type="button"
            onClick={markAll}
            className="rounded-control border border-border-solid/20 px-3 py-1.5 text-xs text-content-secondary hover:text-content-primary"
          >
            Mark all as read
          </button>
        </div>
      )}
      {notifications.length === 0 ? (
        <p className="text-sm text-content-secondary">No notifications.</p>
      ) : (
        <ul className="divide-y divide-border-solid/10 rounded-surface border border-border-solid/15">
          {notifications.map((n) => (
            <li key={n.id} className={`flex items-start justify-between gap-4 px-4 py-3 ${n.read ? "opacity-70" : ""}`}>
              <span className="min-w-0">
                <span className="flex items-center gap-2">
                  <span className={`rounded-pill px-2 py-0.5 text-[10px] font-semibold uppercase ${tone[n.kind] ?? tone.system}`}>{n.kind}</span>
                  <span className="truncate text-sm font-medium text-content-primary">{n.title}</span>
                </span>
                <span className="mt-1 block text-xs text-content-secondary">{n.body}</span>
                <span className="mt-0.5 block text-[10px] text-content-secondary">{new Date(n.at).toLocaleString()}</span>
              </span>
              {!n.read && (
                <button
                  type="button"
                  onClick={() => markRead(n.id)}
                  className="shrink-0 rounded-control border border-border-solid/20 px-2 py-1 text-xs text-content-secondary hover:text-content-primary"
                >
                  Mark read
                </button>
              )}
            </li>
          ))}
        </ul>
      )}
      <SimNote>
        Educational clone — reconstructs the NotificationGallery route observed in the production
        bundle. Notifications are local fixtures plus events generated by simulated actions.
      </SimNote>
    </AppPage>
  );
}
